export function normalizeLocationKey(name) {
  return String(name ?? '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim()
    .replace(/^(estado|cidade|regiao) de\s+/, '')
}

export const GEO_PLACES = Object.fromEntries(PLACES.map(([key, lat, lng, label]) => [key, { lat, lng, label }]))

const GEO_ALIASES = Object.fromEntries(PLACES.flatMap(([key, lat, lng, label, aliases = []]) => (
  [key, ...aliases].map((alias) => [normalizeLocationKey(alias), { lat, lng, label, key }])
)))

export function resolveLocation(name) {
  const key = normalizeLocationKey(name)
  return GEO_ALIASES[key] ?? null
}
